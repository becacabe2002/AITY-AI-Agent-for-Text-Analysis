"""Alembic migrations on a real PostgreSQL (ADR-004 §7.9), opt-in.

* upgrade head -> downgrade base -> upgrade head works on an empty database;
* the migrated schema equals aity_web.db.tables (no drift between the
  migrations - autogenerated, then reviewed - and the metadata the
  repositories use). This is the safety net for what a review can miss,
  e.g. a CHECK change on an existing table that autogenerate does not detect;
* downgrade base leaves no application tables behind;
* the database itself refuses rows that break ownership, even if a
  repository check were ever skipped.

Every test leaves the database at head, so the contract suite can follow.
"""

from __future__ import annotations

import asyncio
from datetime import datetime, timezone
from uuid import uuid4

import pytest
from alembic.autogenerate import compare_metadata
from alembic.migration import MigrationContext
from alembic.script import ScriptDirectory
from sqlalchemy import inspect, insert, pool, text
from sqlalchemy.exc import IntegrityError

from aity_web.db import make_engine, metadata
from aity_web.db.migrate import alembic_config, downgrade, upgrade
from aity_web.db.tables import documents, sessions, users

APP_TABLES = {"users", "sessions", "documents", "analysis_results"}
T0 = datetime(2026, 11, 25, 10, 0, tzinfo=timezone.utc)


def _run(coro_fn, url):
    async def main():
        engine = make_engine(url, poolclass=pool.NullPool)
        try:
            async with engine.connect() as conn:
                return await coro_fn(conn)
        finally:
            await engine.dispose()

    return asyncio.run(main())


def _tables(url) -> set[str]:
    async def go(conn):
        return set(await conn.run_sync(lambda c: inspect(c).get_table_names()))

    return _run(go, url)


def _diff(url) -> list:
    async def go(conn):
        return await conn.run_sync(
            lambda c: compare_metadata(MigrationContext.configure(c), metadata)
        )

    return _run(go, url)


def _current(url) -> str | None:
    async def go(conn):
        return await conn.run_sync(lambda c: MigrationContext.configure(c).get_current_revision())

    return _run(go, url)


@pytest.fixture
def at_head(db_url):
    yield db_url
    upgrade(db_url)


def test_single_linear_history():
    script = ScriptDirectory.from_config(alembic_config())
    assert script.get_heads() == ["0001"]
    assert [r.revision for r in script.walk_revisions()] == ["0001"]


def test_upgrade_downgrade_upgrade(at_head):
    url = at_head
    downgrade(url)
    assert _tables(url) & APP_TABLES == set()
    assert _current(url) is None

    upgrade(url)
    assert APP_TABLES <= _tables(url)
    assert _current(url) == "0001"

    downgrade(url)
    assert _tables(url) - {"alembic_version"} == set()

    upgrade(url)
    assert _current(url) == "0001"


def test_migrated_schema_matches_metadata(at_head):
    url = at_head
    downgrade(url)
    upgrade(url)
    assert _diff(url) == []


def test_database_refuses_cross_user_rows(at_head):
    """A document in another user's session, or a duplicate username,
    is refused by the database itself."""
    url = at_head
    upgrade(url)
    alice, bob, sid = uuid4(), uuid4(), uuid4()

    async def go(conn):
        await conn.execute(text("TRUNCATE analysis_results, documents, sessions, users CASCADE"))
        await conn.execute(insert(users), [
            {"id": alice, "username": "alice", "password_hash": "h", "created_at": T0},
            {"id": bob, "username": "bob", "password_hash": "h", "created_at": T0},
        ])
        await conn.execute(insert(sessions).values(
            id=sid, user_id=alice, name="s", description=None, created_at=T0, updated_at=T0))
        await conn.commit()

        doc_id = uuid4()
        with pytest.raises(IntegrityError, match="fk_documents_session"):
            await conn.execute(insert(documents).values(
                id=doc_id, session_id=sid, user_id=bob, original_filename="x.txt",
                source_type="txt", text_path=f"{bob}/{sid}/{doc_id}_x.txt",
                text_sha256="a" * 64, char_count=1, uploaded_at=T0))
        await conn.rollback()

        with pytest.raises(IntegrityError, match="uq_users_username"):
            await conn.execute(insert(users).values(
                id=uuid4(), username="alice", password_hash="h", created_at=T0))
        await conn.rollback()
        await conn.execute(text("TRUNCATE users CASCADE"))
        await conn.commit()

    _run(go, url)
